from typing import Protocol
from uuid import UUID

from inventory.application.dto.reservation import ReservationDTO, StockAvailabilityDTO
from inventory.domain.entities.ingredient import Ingredient
from inventory.domain.entities.reservation import ReservationRequest
from inventory.domain.entities.warehouse import Warehouse
from inventory.domain.value_objects.quantity import Quantity


class ReservationRepository(Protocol):
    def order_source_is_active(self, business_id: int, order_id: int) -> bool: ...
    def order_reservation_matches(self, business_id: int, order_id: int, lines) -> bool: ...
    def lock_scope(self, business_id: int, warehouse_id: int, ingredient_ids: list[int]) -> tuple[Warehouse | None, dict[int, Ingredient]]: ...
    def get_by_idempotency_key(self, business_id: int, key: UUID, *, lock: bool = False) -> ReservationDTO | None: ...
    def get_for_business(self, business_id: int, reservation_id: int, *, lock: bool = False) -> ReservationDTO | None: ...
    def lock_stock_positions(self, business_id: int, warehouse_id: int, ingredient_ids: list[int]) -> dict[int, Quantity | None]: ...
    def get_active_reserved(self, business_id: int, warehouse_id: int, ingredient_ids: list[int]) -> dict[int, Quantity]: ...
    def create(self, request: ReservationRequest, fingerprint: str, actor_id: int) -> ReservationDTO: ...
    def release(self, business_id: int, reservation_id: int, actor_id: int, idempotency_key: UUID, reason: str) -> ReservationDTO: ...
    def list_for_business(self, business_id: int, *, source_type: str | None, source_id: int | None, status: str | None, page: int, page_size: int) -> tuple[int, list[ReservationDTO]]: ...
    def availability(self, business_id: int, warehouse_id: int, ingredient_id: int) -> StockAvailabilityDTO | None: ...
